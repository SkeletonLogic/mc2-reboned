# Generates cmake/sources-*.cmake from the original VS2005 .vcproj files.
#
# The .vcproj files are the authoritative statement of what the shipped build
# compiled -- globbing the source tree would pick up files that were never in
# any project. This script is re-runnable so the lists can be regenerated and
# diffed if the pristine drop is ever re-synced.
#
# It also resolves each path to its real on-disk casing, because the .vcproj
# files disagree with the filesystem in places (e.g. "GUI\AANIM.CPP"). Windows
# does not care; a case-sensitive host (Emscripten later) very much does.

param(
  [string]$Pristine = (Join-Path $PSScriptRoot "..\..\pristine-microsoft\Source"),
  [string]$PortRoot = (Join-Path $PSScriptRoot "..")
)

$ErrorActionPreference = "Stop"

# target name -> @{ Proj = <vcproj rel to $Pristine>; Base = <dir rel to src/game> }
$targets = [ordered]@{
  "stuff"    = @{ Proj = "MCLib\Stuff\Stuff.vcproj"; Base = "MCLib/Stuff" }
  "mlr"      = @{ Proj = "MCLib\MLR\MLR.vcproj";     Base = "MCLib/MLR"   }
  "gosfx"    = @{ Proj = "MCLib\GOSFX\gosFX.vcproj"; Base = "MCLib/GOSFX" }
  "mclib"    = @{ Proj = "MCLib\MCLib.vcproj";       Base = "MCLib"       }
  "mechcmd2" = @{ Proj = "MechCmd2.vcproj";          Base = ""            }
}

$gameRoot = Join-Path $PortRoot "src\game"
$outDir   = Join-Path $PortRoot "cmake"
New-Item -ItemType Directory -Force -Path $outDir | Out-Null

# Build a case-insensitive lookup of every real file under src/game, so we can
# map a .vcproj's spelling back to the actual on-disk name.
$realByLower = @{}
Get-ChildItem $gameRoot -Recurse -File -Include *.cpp,*.c | ForEach-Object {
  $rel = $_.FullName.Substring($gameRoot.Length + 1) -replace '\\', '/'
  $realByLower[$rel.ToLowerInvariant()] = $rel
}

$summary = @()

foreach ($name in $targets.Keys) {
  $t = $targets[$name]
  [xml]$x = Get-Content (Join-Path $Pristine $t.Proj)

  $resolved = @()
  $missing  = @()

  foreach ($f in $x.SelectNodes("//File")) {
    $rp = $f.RelativePath
    if ($rp -notmatch '\.(cpp|c|cxx)$') { continue }

    # Skip files the project itself excluded from every configuration.
    $cfgs = @($f.SelectNodes("FileConfiguration"))
    if ($cfgs.Count -gt 0 -and @($cfgs | Where-Object { $_.ExcludedFromBuild -ne 'true' }).Count -eq 0) {
      continue
    }

    $rel = $rp -replace '^\.\\', '' -replace '\\', '/'
    if ($t.Base) { $rel = "$($t.Base)/$rel" }

    $key = $rel.ToLowerInvariant()
    if ($realByLower.ContainsKey($key)) { $resolved += $realByLower[$key] }
    else { $missing += $rel }
  }

  $resolved = $resolved | Sort-Object -Unique

  $lines = @()
  $lines += "# Generated by tools/gen-source-lists.ps1 -- do not edit by hand."
  $lines += "# Source of truth: $($t.Proj) (Visual Studio 2005)."
  $lines += "set(MC2_${name}_SOURCES"
  foreach ($r in $resolved) { $lines += "    `${MC2_GAME_DIR}/$r" }
  $lines += ")"
  $outFile = Join-Path $outDir "sources-$name.cmake"
  Set-Content -Path $outFile -Value $lines -Encoding utf8

  $summary += [pscustomobject]@{
    Target  = $name
    Sources = $resolved.Count
    Missing = $missing.Count
  }
  if ($missing.Count -gt 0) {
    Write-Output "  !! $name : $($missing.Count) path(s) in the vcproj have no file on disk:"
    $missing | ForEach-Object { Write-Output "       $_" }
  }
}

$summary | Format-Table -AutoSize
"TOTAL SOURCES: {0}" -f (($summary | Measure-Object Sources -Sum).Sum)
